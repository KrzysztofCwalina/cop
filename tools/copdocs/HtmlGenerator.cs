function submitToCopilot() {
  const keys = Object.keys(comments);
  if (keys.length === 0) {
    alert('No comments to submit.');
    return;
  }

  // Group comments by package
  const grouped = {};
  for (const [key, value] of Object.entries(comments)) {
    const parts = key.split('.');
    const pkg = parts[0];
    if (!grouped[pkg]) grouped[pkg] = [];
    const itemPath = parts.slice(1).join('.');
    grouped[pkg].push({ item: itemPath, comment: value });
  }

  // Build a prompt for Copilot CLI
  let prompt = `Process these ${keys.length} review comment(s) from the cop review app. `;
  prompt += `Each comment is an actionable request to rename, remove, or fix an API in the corresponding .cop package file.\n\n`;

  for (const [pkg, items] of Object.entries(grouped)) {
    prompt += `## ${pkg}\n`;
    for (const item of items) {
      prompt += `- ${item.item}: ${item.comment}\n`;
    }
    prompt += '\n';
  }

  navigator.clipboard.writeText(prompt).then(() => {
    // Auto-clear after successful copy
    comments = {};
    saveComments();
    updateBadge();
    alert(`Copied ${keys.length} comment(s) to clipboard and cleared queue.\nPaste into Copilot CLI.`);
    const active = document.querySelector('.tree-label.active');
    if (active) active.click();
  }).catch(() => {
    const ta = document.createElement('textarea');
    ta.value = prompt;
    document.body.appendChild(ta);
    ta.select();
    document.execCommand('copy');
    document.body.removeChild(ta);
    comments = {};
    saveComments();
    updateBadge();
    alert(`Copied ${keys.length} comment(s) to clipboard and cleared queue.\nPaste into Copilot CLI.`);
  });
}

function formatParamsWithLinks(currentPkgId, paramsStr) {
  if (!paramsStr) return '';
  // Split params by comma, link type references in each segment
  return paramsStr.split(',').map(p => {
    p = p.trim();
    // Match patterns like "name: Type?" or "[Type]?" or just "Type"
    const colonMatch = p.match(/^(\w+):\s*(.+)$/);
    if (colonMatch) {
      return `${escapeHtml(colonMatch[1])}: ${formatTypeLink(currentPkgId, colonMatch[2])}`;
    }
    return formatTypeLink(currentPkgId, p);
  }).join(', ');
}

function formatTypeLink(currentPkgId, typeStr) {
  // First check if the exact string is a registered type (e.g. "[T]")
  const exactLink = makeTypeLink(currentPkgId, typeStr);
  if (exactLink !== typeStr) return exactLink;
  // Handle nullable collection types like [Statement]?
  const nullCollMatch = typeStr.match(/^\[(.+)\]\?$/);
  if (nullCollMatch) {
    const inner = nullCollMatch[1];
    const link = makeTypeLink(currentPkgId, inner);
    return `[${link}]?`;
  }
  // Handle collection types like [Statement], [Folder]
  const collMatch = typeStr.match(/^\[(.+)\]$/);
  if (collMatch) {
    const inner = collMatch[1];
    const link = makeTypeLink(currentPkgId, inner);
    return `[${link}]`;
  }
  // Handle nullable types like File?, string?
  const nullMatch = typeStr.match(/^(.+)\?$/);
  if (nullMatch) {
    const inner = nullMatch[1];
    const link = makeTypeLink(currentPkgId, inner);
    return `${link}?`;
  }
  return makeTypeLink(currentPkgId, typeStr);
}

function makeTypeLink(currentPkgId, typeName) {
  // Find which package owns this type
  for (const [pkgId, pkg] of Object.entries(packages)) {
    if (pkg.types && pkg.types[typeName]) {
      return `<a href="#" class="type-nav-link" data-pkg="${pkgId}" data-type="${typeName}">${typeName}</a>`;
    }
    // Check enums
    if (pkg.enums && pkg.enums.some(e => e.name === typeName)) {
      return `<a href="#" class="type-nav-link" data-pkg="${pkgId}" data-view="enums">${typeName}</a>`;
    }
  }
  // Not found as a navigable type — render plain
  return typeName;
}

