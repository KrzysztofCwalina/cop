using System.Text.Json;
using System.Text.Json.Serialization;

/// <summary>
/// Generates the cop-reference.html file from extracted package data.
/// </summary>
public class HtmlGenerator
{
    public void Generate(ReferenceData data, string outputPath)
    {
        using var writer = new StreamWriter(outputPath, false, System.Text.Encoding.UTF8);
        writer.NewLine = "\n";

        writer.Write(Header.ReplaceLineEndings("\n"));
        writer.Write("\n");

        // Categories
        writer.Write("// === PACKAGE DATA (generated by copdocs) ===\n");
        writer.Write("const categories = ");
        var catOptions = new JsonSerializerOptions
        {
            WriteIndented = true,
            PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
            DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull
        };
        writer.Write(JsonSerializer.Serialize(data.Categories, catOptions));
        writer.Write(";\n\n");

        // Packages
        writer.Write("const packages = ");
        var pkgOptions = new JsonSerializerOptions
        {
            WriteIndented = true,
            DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
            Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping
        };
        writer.Write(JsonSerializer.Serialize(data.Packages, pkgOptions));
        writer.Write(";\n");

        writer.Write(Footer.ReplaceLineEndings("\n"));
    }

