function wireUpComments(container) {
  container.querySelectorAll('.comment-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      const key = btn.dataset.key;
      const input = container.querySelector(`.comment-input[data-key="${CSS.escape(key)}"]`);
      input.classList.toggle('visible');
      if (input.classList.contains('visible')) input.focus();
    });
  });

  container.querySelectorAll('.comment-input').forEach(input => {
    input.addEventListener('input', () => {
      const key = input.dataset.key;
      const btn = container.querySelector(`.comment-btn[data-key="${CSS.escape(key)}"]`);
      if (input.value.trim()) {
