function highlightCop(code) {
  // Normalize line endings to avoid extra blank lines in <pre>
  code = code.replace(/\r\n/g, '\n').replace(/\r/g, '\n');
  // Escape HTML first
  code = code.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  // Comments (must come first, before other replacements interfere)
  code = code.replace(/(#[^\n]*)/g, '<span class="cop-comment">$1</span>');
  // Strings (single-quoted)
  code = code.replace(/'([^'\\]*(?:\\.[^'\\]*)*)'/g, '<span class="cop-str">\'$1\'</span>');
  // Template interpolation {item.Name} inside already-processed text
  code = code.replace(/\{([^}@]+)\}/g, '<span class="cop-template">{$1}</span>');
  // Keywords (must match tokenizer: type/collection/import/let/command/export/predicate/function/foreach/feed/flags/enum)
  code = code.replace(/\b(import|predicate|function|let|foreach|type|export|command|enum|flags|collection|feed|async)\b/g, '<span class="cop-kw">$1</span>');
  // Built-in actions (language-level uppercase commands)
  code = code.replace(/\b(PRINT|SAVE|RUN|DEBUG|ASSERT|FAIL)\b/g, '<span class="cop-kw">$1</span>');
  // Built-in functions and collection transforms
  code = code.replace(/\b(Where|Select|GroupBy|OrderBy|OrderByDescending|Sum|Average|Count|Reduce|Distinct|Min|Max|Get|File|Text|Path|Matches)\b/g, '<span class="cop-fn">$1</span>');
  // Predicate calls (:name)
  code = code.replace(/:([a-zA-Z][a-zA-Z0-9]*)/g, ':<span class="cop-pred">$1</span>');
  // Operators
  code = code.replace(/(\=&gt;|&amp;&amp;|\|\||\|&gt;)/g, '<span class="cop-op">$1</span>');
  // Numbers
  code = code.replace(/\b(\d+)\b/g, '<span class="cop-num">$1</span>');
  return code;
}

function escapeHtml(str) {
  if (!str) return '';
  return str.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

// Returns true if the function has a type page (i.e., appliesTo matches a defined type in some package)
// Generic collection functions ([T]) should appear in both the Functions section and the [T] type page
function hasTypePage(fn) {
  if (!fn.appliesTo) return false;
  // [T] is the universal collection type — don't hide these from Functions
  if (fn.appliesTo === '[T]') return false;
  for (const p of Object.values(packages)) {
    if (p.types && p.types[fn.appliesTo]) return true;
  }
  return false;
}

function sourceLink(url) {
  if (!url) return '';
  return `<a href="${url}" target="_blank" class="source-link" title="View source">📄</a>`;
}

